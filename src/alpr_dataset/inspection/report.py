"""Aggregate scan + hashing + image-stats results into Part 1 deliverables:

    reports/eda/dataset_summary.md
    reports/eda/dataset_summary.csv
"""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd
from tqdm import tqdm

from alpr_dataset.inspection.hashing import find_duplicates
from alpr_dataset.inspection.image_stats import batch_compute_stats
from alpr_dataset.inspection.scanner import DatasetScanResult, scan_dataset
from alpr_dataset.io_utils import ensure_dir

logger = logging.getLogger("alpr_dataset")


def _duplicate_filenames(image_paths: list[Path]) -> dict[str, list[Path]]:
    """Filenames (not content) that repeat across the dataset tree."""
    by_name: dict[str, list[Path]] = {}
    for p in image_paths:
        by_name.setdefault(p.name, []).append(p)
    return {k: v for k, v in by_name.items() if len(v) > 1}


def build_dataset_summary_row(
    scan: DatasetScanResult, hamming_threshold: int
) -> dict:
    stats = batch_compute_stats(
        tqdm(scan.image_paths, desc=f"[{scan.dataset_name}] image stats", leave=False)
    )
    valid_stats = [s for s in stats if not s.is_corrupted]
    corrupted = [s for s in stats if s.is_corrupted]

    widths = [s.width for s in valid_stats]
    heights = [s.height for s in valid_stats]
    aspect_ratios = [w / h for w, h in zip(widths, heights) if h > 0]
    file_sizes_kb = [s.file_size_bytes / 1024 for s in valid_stats]
    color_spaces = pd.Series([s.color_space for s in valid_stats]).value_counts().to_dict()

    dup_filenames = _duplicate_filenames(scan.image_paths)
    duplicate_groups = find_duplicates(scan.image_paths, hamming_threshold=hamming_threshold)

    row = {
        "dataset_name": scan.dataset_name,
        "root": str(scan.root),
        "n_images": scan.n_images,
        "n_annotations": scan.n_annotations,
        "n_images_missing_annotations": len(scan.images_missing_annotations),
        "n_orphan_annotations": len(scan.orphan_annotations),
        "n_unsupported_files": len(scan.unsupported_files),
        "n_corrupted_images": len(corrupted),
        "n_duplicate_filenames_groups": len(dup_filenames),
        "n_exact_duplicate_images_groups": len(duplicate_groups.exact_duplicates),
        "n_near_duplicate_pairs": len(duplicate_groups.near_duplicates),
        "image_formats": dict(scan.image_format_counts),
        "annotation_formats": dict(scan.annotation_format_counts),
        "color_space_counts": color_spaces,
        "avg_width": round(sum(widths) / len(widths), 2) if widths else 0,
        "avg_height": round(sum(heights) / len(heights), 2) if heights else 0,
        "min_resolution_wh": f"{min(widths)}x{min(heights)}" if widths and heights else "n/a",
        "max_resolution_wh": f"{max(widths)}x{max(heights)}" if widths and heights else "n/a",
        "avg_aspect_ratio": round(sum(aspect_ratios) / len(aspect_ratios), 3)
        if aspect_ratios
        else 0,
        "avg_file_size_kb": round(sum(file_sizes_kb) / len(file_sizes_kb), 2)
        if file_sizes_kb
        else 0,
        "min_file_size_kb": round(min(file_sizes_kb), 2) if file_sizes_kb else 0,
        "max_file_size_kb": round(max(file_sizes_kb), 2) if file_sizes_kb else 0,
    }
    return row


def generate_dataset_summary(
    dataset_specs: list[tuple[str, Path]],
    output_dir: Path,
    hamming_threshold: int = 5,
) -> pd.DataFrame:
    """Run Part 1 inspection across all datasets and write md + csv reports.

    Args:
        dataset_specs: list of (dataset_name, dataset_root_path).
        output_dir: directory to write dataset_summary.md / .csv into.
        hamming_threshold: perceptual hash distance for near-duplicate flagging.

    Returns:
        DataFrame with one summary row per dataset (also written to CSV).
    """
    output_dir = ensure_dir(output_dir)
    rows = []
    for name, root in dataset_specs:
        scan = scan_dataset(name, root)
        row = build_dataset_summary_row(scan, hamming_threshold=hamming_threshold)
        rows.append(row)

    df = pd.DataFrame(rows)
    csv_path = output_dir / "dataset_summary.csv"
    df.to_csv(csv_path, index=False)
    logger.info("Wrote dataset summary CSV -> %s", csv_path)

    md_path = output_dir / "dataset_summary.md"
    _write_markdown_summary(rows, dataset_specs, md_path)
    logger.info("Wrote dataset summary Markdown -> %s", md_path)

    return df


def _write_markdown_summary(
    rows: list[dict], dataset_specs: list[tuple[str, Path]], md_path: Path
) -> None:
    lines = ["# Dataset Summary Report", ""]
    lines.append(
        "Automatically generated by `alpr_dataset.inspection.report`. "
        "Covers folder structure, formats, counts, and integrity signals "
        "for every configured raw dataset."
    )
    lines.append("")

    for (name, root), row in zip(dataset_specs, rows):
        lines.append(f"## {name}")
        lines.append(f"- Root: `{root}`")
        lines.append(f"- Images: **{row['n_images']}**")
        lines.append(f"- Annotations: **{row['n_annotations']}**")
        lines.append(f"- Images missing annotations: {row['n_images_missing_annotations']}")
        lines.append(f"- Orphan annotations: {row['n_orphan_annotations']}")
        lines.append(f"- Unsupported files: {row['n_unsupported_files']}")
        lines.append(f"- Corrupted images: {row['n_corrupted_images']}")
        lines.append(f"- Duplicate filename groups: {row['n_duplicate_filenames_groups']}")
        lines.append(f"- Exact duplicate image groups: {row['n_exact_duplicate_images_groups']}")
        lines.append(f"- Near-duplicate pairs (phash): {row['n_near_duplicate_pairs']}")
        lines.append(f"- Image formats: {row['image_formats']}")
        lines.append(f"- Annotation formats: {row['annotation_formats']}")
        lines.append(f"- Color spaces: {row['color_space_counts']}")
        lines.append(
            f"- Resolution: avg {row['avg_width']}x{row['avg_height']}, "
            f"min {row['min_resolution_wh']}, max {row['max_resolution_wh']}"
        )
        lines.append(f"- Average aspect ratio: {row['avg_aspect_ratio']}")
        lines.append(
            f"- File size (KB): avg {row['avg_file_size_kb']}, "
            f"min {row['min_file_size_kb']}, max {row['max_file_size_kb']}"
        )
        lines.append("")

    md_path.write_text("\n".join(lines), encoding="utf-8")
